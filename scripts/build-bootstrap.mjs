// Generate self-contained, dependency-free first-install scripts from reviewed sources.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const root = resolve(import.meta.dirname, '..');
const require = createRequire(join(root, 'app', 'package.json'));
const ts = require('typescript');
export function payload() {
  const files = {};
  for (const file of ['bootstrap/main.mjs', 'bootstrap/service-request.mjs', 'bootstrap/records.mjs', 'bootstrap/registry.mjs', 'bootstrap/windows-files.ps1', 'bootstrap/windows-owner.ps1', 'bootstrap/windows-launcher.ps1', 'bootstrap/windows-parent-witness.ps1', 'app/desktop/maintenance.mjs']) {
    const source = readFileSync(join(root, file), 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
    // -File in Windows PowerShell 5.1 requires a BOM to detect UTF-8.
    files[file] = file.endsWith('.ps1') ? '\uFEFF' + source : source;
  }
  for (const file of ['server/process-owner-record', 'server/process-owner-linux-identity', 'server/owned-process-linux', 'shared/maintenance']) {
    const source = readFileSync(join(root, 'app/src', file + '.ts'), 'utf8');
    const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, newLine: ts.NewLineKind.LineFeed }, fileName: file + '.ts', reportDiagnostics: true });
    assert.equal(compiled.diagnostics?.length || 0, 0, `Bootstrap transpilation failed: ${file}`);
    files[`app/dist/${file}.mjs`] = compiled.outputText.replace(/(from\s+["'][^"']+)\.js(["'])/g, '$1.mjs$2');
  }
  return files;
}
export function generate() {
  const encoded = Buffer.from(JSON.stringify(payload())).toString('base64');
  const ps = `# Generated by scripts/build-bootstrap.mjs; edit bootstrap/ sources instead.
# Requires Node.js 22.19.0+. Windows PowerShell 5.1 and PowerShell 7.
$ErrorActionPreference = 'Stop'
if (-not (Get-Command node -ErrorAction SilentlyContinue)) { throw 'Install Node.js 22.19.0+ from https://nodejs.org/ and reopen PowerShell, then retry.' }
$axiomNodeVersion = & node --version
if ($LASTEXITCODE -ne 0 -or [version]($axiomNodeVersion.Trim().TrimStart('v')) -lt [version]'22.19.0') { throw 'Axiom2 requires Node.js 22.19.0+.' }
$axiomRuntimeEncoded = @'
const fs = require('node:fs'), path = require('node:path'), os = require('node:os');
const root = path.resolve(process.env.AXIOM_DATA_DIR || path.join(os.homedir(), '.axiom2'));
const runtime = path.join(root, 'bootstrap', 'runtimes', require('node:crypto').randomUUID().replaceAll('-', ''));
const files = JSON.parse(Buffer.from('${encoded}', 'base64').toString('utf8'));
fs.mkdirSync(path.toNamespacedPath(runtime), { recursive: true, mode: 0o700 });
for (const [name, text] of Object.entries(files)) {
  const target = path.toNamespacedPath(path.join(runtime, name));
  fs.mkdirSync(path.dirname(target), { recursive: true, mode: 0o700 });
  fs.writeFileSync(target, text, { flag: 'wx', mode: 0o600 });
}
process.stdout.write(Buffer.from(runtime, 'utf8').toString('base64'));
'@ | & node -
if ($LASTEXITCODE -ne 0) { throw 'Axiom2 bootstrap extraction failed. No installation was started.' }
$axiomRuntime = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($axiomRuntimeEncoded))
& node ($axiomRuntime + '\\bootstrap\\main.mjs') install
if ($LASTEXITCODE -ne 0) { throw 'Axiom2 installation did not complete. Inspect the printed maintenance record. Service was not started.' }
$axiomHandoffEncoded = @'
const fs = require('node:fs'), path = require('node:path');
process.stdout.write(fs.readFileSync(path.toNamespacedPath(process.argv[2])).toString('base64'));
'@ | & node - ($axiomRuntime + '\\handoff.json')
if ($LASTEXITCODE -ne 0) { throw 'Axiom2 installation handoff could not be read. Service was not started.' }
$axiomHandoff = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($axiomHandoffEncoded)) | ConvertFrom-Json
& (Join-Path $axiomHandoff.prefix 'axiom2.cmd') start
if ($LASTEXITCODE -ne 0) { throw 'Axiom2 exited with an error.' }
`;
  const sh = `#!/bin/sh
# Generated by scripts/build-bootstrap.mjs; edit bootstrap/ sources instead.
set -eu
if ! command -v node >/dev/null 2>&1; then
  echo 'Install Node.js 22.19.0+ from https://nodejs.org/ and reopen your terminal, then retry.' >&2
  exit 1
fi
if ! node -e 'const [major, minor] = process.versions.node.split(".").map(Number); if (major < 22 || (major === 22 && minor < 19)) process.exit(1)'; then
  echo 'Axiom2 requires Node.js 22.19.0+.' >&2
  exit 1
fi
axiom_root=\${AXIOM_DATA_DIR:-"$HOME/.axiom2"}
mkdir -p "$axiom_root/bootstrap/runtimes"
axiom_runtime=$(mktemp -d "$axiom_root/bootstrap/runtimes/install-XXXXXXXX")
node - "$axiom_runtime" <<'AXIOM_BOOTSTRAP_PAYLOAD'
const fs = require('node:fs'), path = require('node:path');
const files = JSON.parse(Buffer.from('${encoded}', 'base64').toString('utf8'));
for (const [name, text] of Object.entries(files)) {
  const target = path.join(process.argv[2], name);
  fs.mkdirSync(path.dirname(target), {recursive:true,mode:0o700});
  fs.writeFileSync(target, text, {flag:'wx',mode:0o600});
}
AXIOM_BOOTSTRAP_PAYLOAD
node "$axiom_runtime/bootstrap/main.mjs" install
axiom_prefix=$(node -e 'console.log(JSON.parse(require("node:fs").readFileSync(process.argv[1],"utf8")).prefix)' "$axiom_runtime/handoff.json")
exec "$axiom_prefix/bin/axiom2" start
`;
  return { 'install.ps1': ps, 'install.sh': sh, 'app/desktop/setup-runtime.json': JSON.stringify(payload()) + '\n' };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (process.argv[2] === '--output') {
    assert.ok(process.argv[3]);
    for (const [file, text] of Object.entries(payload())) { const target = join(resolve(process.argv[3]), file); mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, text); }
  } else for (const [file, text] of Object.entries(generate())) {
    if (process.argv.includes('--check')) assert.equal(readFileSync(join(root, file), 'utf8').replace(/\r\n/g, '\n'), text, `${file} is stale; run node scripts/build-bootstrap.mjs`);
    else writeFileSync(join(root, file), text);
  }
}
