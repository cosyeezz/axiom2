import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium } from "playwright";
import { startServer } from "../src/server/index.js";
import { memoryDirectory } from "../src/server/memory-files.js";
import type { Workspace, Session, Command } from "../src/shared/protocol.js";
const root = mkdtempSync(join(tmpdir(), "axiom-processing-ui-")), project = join(root, "project"); mkdirSync(project);
const previous = process.env.AXIOM_PI_DIR; process.env.AXIOM_PI_DIR = join(root, "pi");
const app = await startServer({ root, port: 0, dev: true });
const browser = await chromium.launch({ executablePath: process.env.AXIOM_TEST_BROWSER });
const output = "/tmp/axiom-processing-ui"; mkdirSync(output, { recursive: true });
try {
  const workspace = app.store.execute({ requestId: randomUUID(), op: "workspace.open", params: { path: project, authorized: true } }) as Workspace;
  const session = app.store.execute({ requestId: randomUUID(), op: "session.create", workspaceId: workspace.id }) as Session;
  const scope = { workspaceId: workspace.id, sessionId: session.id }, memory = app.agents.memories, records = memory.records;
  writeFileSync(join(memoryDirectory(root, session.id), "MEMORY.md"), "# 当前依据\n记录来源"); memory.scan(scope);
  for (let i = 0; i < 53; i++) { const id = records.start(scope, "memory.query", `查询 ${i}`); records.finish(id, "completed"); }
  const id = records.start(scope, "memory.organize", "模型完成但解析失败"), call = records.callStart(id, "整理文件：MEMORY.md", "输入正文");
  records.callSent(id, call); records.callFinish(id, call, "我会完整读取会话记忆\n" + "长响应".repeat(2000)); records.stage(id, "解析输出：MEMORY.md"); records.finish(id, "failed", "整理输出格式错误：模型应直接返回JSON数组");
  const entry = memory.catalog(workspace.id)[0]!;
  app.store.db.prepare("UPDATE memory_sources SET body=? WHERE sessionId=?").run(JSON.stringify({ ...entry, status: "error", error: "旧请求格式错误，缺少原始响应" }), session.id);
  const compressionId = records.start(scope, "compression", "压缩失败"), compressionCall = records.callStart(compressionId, "生成摘要", "压缩输入"); records.callFinish(compressionId, compressionCall, "压缩响应"); records.stage(compressionId, "应用摘要"); records.finish(compressionId, "failed", "摘要应用失败");
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } }), errors: string[] = [], commands: Command[] = [];
  page.on("pageerror", (error) => errors.push(error.message)); page.on("websocket", (socket) => socket.on("framesent", ({ payload }) => { const message = JSON.parse(payload.toString()); if (message.op) commands.push(message); }));
  await page.addInitScript((value) => sessionStorage.setItem("view", JSON.stringify(value)), scope);
  await page.goto(app.origin); await page.getByRole("button", { name: "全局记忆", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "全局记忆", exact: true }); await dialog.waitFor();
  await dialog.getByLabel("搜索记忆").fill("保留筛选");
  await dialog.getByRole("button", { name: "放大记忆树" }).click();
  await dialog.getByRole("button", { name: "处理记录", exact: true }).click();
  const recordsPage = dialog.getByRole("region", { name: "处理记录", exact: true });
  await recordsPage.locator(".processing-row").first().waitFor();
  assert.equal(await recordsPage.locator(".processing-row").count(), 50);
  await recordsPage.getByRole("button", { name: "下一页", exact: true }).click();
  await recordsPage.getByText("第 2 页", { exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelectorAll('.processing-row').length === 5);
  await recordsPage.getByLabel("处理类型").selectOption("memory.organize");
  await recordsPage.getByRole("button", { name: /模型完成但解析失败/ }).click();
  const detail = recordsPage.getByRole("article", { name: "处理详情" }); await detail.getByRole("heading", { name: "处理失败原因" }).waitFor();
  assert.match(await detail.innerText(), /解析输出：MEMORY.md/); assert.match(await detail.innerText(), /成功/);
  await detail.locator("summary").filter({ hasText: "模型原始响应" }).click();
  assert.match(await detail.locator("pre").last().innerText(), /我会完整读取会话记忆/);
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 }); await page.waitForTimeout(100);
    assert.equal(await dialog.evaluate((node) => node.scrollWidth > node.clientWidth + 1), false, `dialog overflow at ${width}`);
    assert.equal(await detail.evaluate((node) => node.scrollWidth > node.clientWidth + 1), false, `detail overflow at ${width}`);
    await page.screenshot({ path: join(output, `records-${width}.png`) });
  }
  await recordsPage.getByRole("button", { name: "返回", exact: true }).click();
  assert.equal(await dialog.getByLabel("搜索记忆").inputValue(), "保留筛选"); assert.match(await dialog.locator(".memory-tree-zoom").innerText(), /110%/);
  await dialog.locator(".memory-tree-errors summary").click(); await dialog.getByRole("button", { name: "查看详情", exact: true }).click();
  await recordsPage.getByText(/来源当前错误：旧请求格式错误/).waitFor();
  await dialog.getByRole("button", { name: "关闭记忆", exact: true }).click();
  const legacyId = randomUUID();
  records.syncCompression(scope, { id: legacyId, state: "failed", phase: "summarizing", startedAt: 1000, endedAt: 2000, error: "历史摘要生成错误", summary: "", selection: { provider: "fixture", id: "fixture" } });
  await page.locator('[data-od-id="background-compression-trigger"]').click();
  const compression = page.getByRole("dialog", { name: "后台压缩", exact: true }); await compression.getByRole("button", { name: "处理记录", exact: true }).click();
  await compression.getByRole("button", { name: /压缩失败/ }).click();
  await compression.getByRole("heading", { name: "处理失败原因" }).waitFor();
  assert.match(await compression.getByRole("article", { name: "处理详情" }).innerText(), /摘要应用失败/);
  await compression.getByRole("button", { name: "返回记录列表", exact: true }).click();
  await compression.getByRole("button", { name: /历史摘要生成错误/ }).click();
  const legacyDetail = compression.getByRole("article", { name: "处理详情" });
  await legacyDetail.getByText("未记录阶段时间", { exact: true }).waitFor();
  assert.equal(await legacyDetail.locator("ol li").count(), 0);
  assert.match(await legacyDetail.innerText(), /1\.0 秒/);
  assert.equal(commands.some((command) => ["compression.start", "memory.organize", "prompt", "memory.query"].includes(command.op)), false, "browsing does not invoke models");
  assert.deepEqual(errors, []); console.log("Processing UI passed: entries, legacy error, parse failure, full response, pagination/filter, retained memory state, compression, four widths, no model requests");
} finally { await browser.close(); await app.close(); rmSync(root, { recursive: true, force: true }); if (previous === undefined) delete process.env.AXIOM_PI_DIR; else process.env.AXIOM_PI_DIR = previous; }
