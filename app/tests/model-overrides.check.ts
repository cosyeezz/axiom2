import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium, type Browser, type Locator } from "playwright";
import { startServer } from "../src/server/index.js";
import { assertSelectPosition } from "./select-helpers.js";

const root = mkdtempSync(join(tmpdir(), "axiom-overrides-ui-"));
const artifacts = process.env.AXIOM_OVERRIDES_ARTIFACTS ?? "/tmp/axiom-overrides-ui-artifacts";
mkdirSync(artifacts, { recursive: true });
const previous = process.env.AXIOM_PI_DIR;
process.env.AXIOM_PI_DIR = join(root, "pi");
let app: Awaited<ReturnType<typeof startServer>> | undefined, browser: Browser | undefined;
try {
  app = await startServer({ root: join(root, "data"), port: 0, dev: true });
  browser = await chromium.launch({ executablePath: process.env.AXIOM_TEST_BROWSER });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort());
  await page.goto(app.origin + "/model-config.html");
  const pick = async (region: Locator, label: string, value: string) => {
    await region.getByRole("button", { name: label + "备选项", exact: true }).click();
    await page.getByRole("option", { name: value, exact: true }).click();
  };
  const save = async () => {
    await page.locator("#save-provider").click();
    await page.locator(".configuration-feedback[data-saved=true]").waitFor();
  };
  const disk = () => JSON.parse(readFileSync(join(root, "pi", "models.json"), "utf8")).providers["overrides-ui"];
  await page.locator("#add-supplier").click();
  await page.getByRole("menuitem", { name: "自定义接口", exact: true }).click();
  await page.locator("#provider-id").fill("overrides-ui");
  await page.locator("#provider-name").fill("覆盖编辑验证");
  await page.locator("#provider-url").fill("http://127.0.0.1:1/v1");
  const providerHeaders = page.getByRole("region", { name: "供应商请求头覆盖", exact: true });
  await providerHeaders.getByRole("button", { name: "添加一项" }).click();
  await providerHeaders.getByRole("combobox", { name: "第 1 项 key", exact: true }).fill("constructor");
  await providerHeaders.getByRole("combobox", { name: "第 1 项 key", exact: true }).fill("__proto__");
  await pick(providerHeaders, "第 1 项 key", "Content-Type");
  await pick(providerHeaders, "第 1 项 value", "application/json");
  await providerHeaders.getByRole("button", { name: "添加一项" }).click();
  await providerHeaders.getByRole("combobox", { name: "第 2 项 key", exact: true }).fill("X-Custom-Text");
  await providerHeaders.getByRole("combobox", { name: "第 2 项 value", exact: true }).fill("001 custom");
  await save();
  assert.equal(disk().headers["Content-Type"], "application/json");
  assert.equal(disk().headers["X-Custom-Text"], "001 custom");
  // Opening suggestions and reselecting the same key cannot discard a hidden saved value.
  await pick(providerHeaders, "第 1 项 key", "Content-Type");
  assert.equal(await providerHeaders.getByRole("combobox", { name: "第 1 项 value", exact: true }).inputValue(), "");
  await save();
  assert.equal(disk().headers["Content-Type"], "application/json");
  await page.locator("#models-tab").click();
  await page.locator("#add-model").click();
  await page.locator("#new-model-id").fill("local-model");
  await page.locator("#new-model-name").fill("覆盖模型");
  const body = page.getByRole("region", { name: "请求体覆盖", exact: true });
  await body.getByRole("button", { name: "添加一项" }).click();
  const key = body.getByRole("combobox", { name: "第 1 项请求体字段", exact: true });
  await key.fill("toString");
  await key.fill("service");
  await page.keyboard.press("ArrowDown");
  await page.keyboard.press("Enter");
  assert.equal(await key.inputValue(), "service_tier", "keyboard accepts filtered suggestion");
  await pick(body, "第 1 项请求体值", "fast");
  const value = body.getByRole("combobox", { name: "第 1 项请求体值", exact: true });
  await value.fill("custom-fast");
  assert.equal(await value.inputValue(), "custom-fast", "suggested values remain freely editable");
  await pick(body, "第 1 项请求体值", "fast");
  await body.getByRole("button", { name: "第 1 项请求体值备选项", exact: true }).click();
  await page.keyboard.press("ArrowDown");
  await page.keyboard.press("Escape");
  assert.equal(await value.inputValue(), "fast", "Escape does not commit the active suggestion");
  await body.getByRole("button", { name: "第 1 项请求体值备选项", exact: true }).click();
  await page.keyboard.press("Tab");
  assert.equal(await page.getByRole("listbox").count(), 0);
  await body.getByRole("button", { name: "添加一项" }).click();
  await pick(body, "第 2 项请求体字段", "temperature");
  await body.getByRole("combobox", { name: "第 2 项请求体值", exact: true }).fill("0.5");
  assert.equal(await body.getByRole("combobox", { name: "第 2 项请求体值类型", exact: true }).innerText(), "数字");
  await body.getByRole("button", { name: "添加一项" }).click();
  await body.getByRole("combobox", { name: "第 3 项请求体字段", exact: true }).fill("custom_text");
  await body.getByRole("combobox", { name: "第 3 项请求体值", exact: true }).fill("  中文 001  ");
  const modelHeaders = page.getByRole("region", { name: "模型请求头覆盖", exact: true });
  await modelHeaders.getByRole("button", { name: "添加一项" }).click();
  await modelHeaders.getByRole("combobox", { name: "第 1 项 key", exact: true }).fill("X-Model");
  await modelHeaders.getByRole("combobox", { name: "第 1 项 value", exact: true }).fill("model-only");
  for (const [width, height] of [[320, 640], [390, 844], [820, 1180], [1440, 1000]]) {
    await page.setViewportSize({ width, height });
    await key.scrollIntoViewIfNeeded();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `page fits ${width}`);
    assert.ok(await page.locator("#model-editor").evaluate(el => el.scrollWidth <= el.clientWidth + 1), `editor fits ${width}`);
    await body.getByRole("button", { name: "第 1 项请求体字段备选项", exact: true }).click();
    await assertSelectPosition(page, key);
    await page.screenshot({ path: join(artifacts, `overrides-${width}.png`) });
    await page.keyboard.press("Escape");
  }
  await page.getByRole("button", { name: "完成编辑", exact: true }).click();
  await save();
  assert.deepEqual(disk().models[0].samplingParams, { service_tier: "fast", temperature: 0.5, custom_text: "  中文 001  " });
  assert.equal(disk().models[0].headers["X-Model"], "model-only");
  await page.reload();
  await page.locator("#models-tab").click();
  await page.locator("#configured-model-table tbody tr").first().hover();
  await page.getByRole("button", { name: "编辑模型：覆盖模型", exact: true }).click();
  assert.equal(await value.inputValue(), "fast");
  assert.equal(await body.getByRole("combobox", { name: "第 3 项请求体值", exact: true }).inputValue(), "  中文 001  ");
  await body.getByRole("button", { name: "删除第 1 项请求体覆盖", exact: true }).click();
  await page.getByRole("button", { name: "完成编辑", exact: true }).click();
  await save();
  assert.equal(disk().models[0].samplingParams.service_tier, undefined);
  // Supplier body overrides are applied to models on save, preserving model-specific values.
  await page.locator("#suppliers-tab").click();
  await body.getByRole("button", { name: "添加一项" }).click();
  await pick(body, "第 1 项请求体字段", "service_tier");
  await pick(body, "第 1 项请求体值", "ultrafast");
  await save();
  assert.equal(disk().models[0].samplingParams.service_tier, "ultrafast");
  const touch = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  const mobile = await touch.newPage();
  mobile.on("pageerror", error => errors.push(error.message));
  await mobile.goto(app.origin + "/model-config.html");
  await mobile.locator("#models-tab").tap();
  await mobile.getByRole("button", { name: "编辑模型：覆盖模型", exact: true }).tap();
  const mobileBody = mobile.getByRole("region", { name: "请求体覆盖", exact: true });
  const tierRow = mobileBody.locator(".override-row").filter({ has: mobile.locator('input[value="service_tier"]') });
  const tierValue = tierRow.getByRole("combobox").last();
  await tierRow.getByRole("button", { name: /请求体值备选项/ }).tap();
  await mobile.getByRole("option", { name: "fast", exact: true }).tap();
  assert.equal(await tierValue.inputValue(), "fast", "touch selects suggested text");
  await tierValue.fill("custom-tier");
  await mobile.getByRole("button", { name: "完成编辑", exact: true }).tap();
  await mobile.locator("#save-provider").tap();
  await mobile.locator(".configuration-feedback[data-saved=true]").waitFor();
  assert.equal(disk().models[0].samplingParams.service_tier, "custom-tier");
  await touch.close();
  assert.deepEqual(errors, []);
  console.log(`PASS override UI: header/body suggestions and free text, keyboard/Escape/Tab, saved-header retention, typed save/reload/deletion, supplier application, four viewport layouts and touch. Artifacts: ${artifacts}`);
} finally {
  await browser?.close();
  await app?.close();
  if (previous === undefined) delete process.env.AXIOM_PI_DIR; else process.env.AXIOM_PI_DIR = previous;
  rmSync(root, { recursive: true, force: true });
}
