import assert from "node:assert/strict";
import { mkdirSync, readFileSync, rmSync } from "node:fs";
import { resolve } from "node:path";
import { randomUUID } from "node:crypto";
import { chromium } from "playwright";
import { startServer } from "../src/server/index.js";
import { rtkConfigPath } from "../src/server/integrations/rtk-config.js";
import { recordRtkEvent } from "../src/server/integrations/rtk-stats.js";
import { rtkFixture } from "./rtk-fixture.js";
const f = rtkFixture();
const app = await startServer({ root: f.root, port: 0, rtk: f, openCli: { locateNpm: () => { throw Error("OpenCLI fixture unavailable"); } } });
const browser = await chromium.launch({ headless: true, executablePath: process.env.AXIOM_TEST_BROWSER });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
try {
  await page.goto(app.origin + "/tools.html#rtk");
  const tool = page.locator("#rtk");
  await tool.getByRole("heading", { name: "RTK", exact: true }).waitFor();
  await tool.getByRole("button", { name: "检查 RTK 更新", exact: true }).click();
  await page.waitForFunction(() => !(document.querySelector('#rtk button.btn-primary') as HTMLButtonElement)?.disabled);
  f.hold(); await tool.getByRole("button", { name: "安装 RTK", exact: true }).click();
  await tool.getByRole("button", { name: "取消操作", exact: true }).waitFor();
  await page.reload(); await tool.getByRole("button", { name: "取消操作", exact: true }).waitFor();
  await tool.getByRole("button", { name: "取消操作", exact: true }).click();
  await tool.getByText("操作已取消；未切换当前版本。", { exact: true }).waitFor();
  f.release();
  await tool.getByRole("checkbox", { name: /启用 RTK/ }).check();
  await tool.getByRole("combobox", { name: "过滤等级", exact: true }).click(); await page.getByRole("option", { name: "强力", exact: true }).click();
  await tool.getByRole("button", { name: "保存过滤设置", exact: true }).click();
  await tool.getByText("请先安装 RTK，再启用过滤。", { exact: true }).waitFor();
  assert.equal(await tool.getByRole("button", { name: "安装 RTK", exact: true }).isEnabled(), true, "unsaved settings must not block installation");
  await tool.getByRole("button", { name: "安装 RTK", exact: true }).click();
  await tool.getByText("安装与自检完成；设置将用于后续工具结果。", { exact: true }).waitFor();
  assert.equal(await tool.getByRole("checkbox", { name: /启用 RTK/ }).isChecked(), true, "installation preserves the enabled draft");
  assert.equal(await tool.getByRole("combobox", { name: "过滤等级" }).innerText(), "强力", "installation preserves the level draft");
  assert.equal(await tool.getByText("配置已在其他窗口修改；当前输入已保留。", { exact: true }).count(), 0, "installation alone is not a settings conflict");
  assert.equal(JSON.parse(readFileSync(rtkConfigPath(f.root), "utf8")).enabled, false, "installation must not implicitly save or enable the draft");
  await page.getByRole("link", { name: /OpenCLI 浏览器/ }).click();
  await page.getByRole("link", { name: /RTK 输出过滤/ }).click();
  assert.equal(await tool.getByRole("combobox", { name: "过滤等级" }).innerText(), "强力", "switching tools preserves draft");
  await tool.getByRole("button", { name: "保存过滤设置", exact: true }).click();
  await tool.getByText("设置已保存，将用于后续工具结果，包括已打开的会话。", { exact: true }).waitFor();
  assert.equal(JSON.parse(readFileSync(rtkConfigPath(f.root), "utf8")).level, "aggressive");
  const other = await browser.newPage(); await other.goto(app.origin + "/tools.html#rtk");
  await other.locator("#rtk").getByRole("checkbox", { name: /启用 RTK/ }).waitFor();
  await page.waitForFunction(() => (document.querySelector('#rtk input[type=checkbox]') as HTMLInputElement).checked);
  await tool.getByRole("checkbox", { name: /同时用于子代理/ }).uncheck();
  await other.locator("#rtk").getByRole("checkbox", { name: /启用 RTK/ }).uncheck();
  await other.locator("#rtk").getByRole("button", { name: "保存过滤设置", exact: true }).click();
  await tool.getByText("配置已在其他窗口修改；当前输入已保留。", { exact: true }).waitFor();
  await tool.getByRole("button", { name: "用当前输入保存", exact: true }).click();
  await tool.getByText("设置已保存，将用于后续工具结果，包括已打开的会话。", { exact: true }).waitFor();
  await other.close();
  recordRtkEvent(f.root, { id: randomUUID(), at: Date.now(), role: "subagent", level: "balanced", filter: "find", reason: "filtered", inputBytes: 4096, outputBytes: 1024, durationMs: 5, version: "1.0.1" });
  await tool.getByRole("button", { name: "刷新效果", exact: true }).click();
  await tool.getByText("3.0 KiB · 75.0%", { exact: true }).waitFor();
  await tool.locator("summary").filter({ hasText: "最近 1 条记录" }).click();
  await tool.getByRole("cell", { name: "已缩减", exact: true }).waitFor();
  await tool.getByRole("button", { name: "运行自检", exact: true }).click();
  await tool.getByText(/版本、UTF-8 stdin 透传和文件列表缩减自检通过/).waitFor();
  mkdirSync(resolve("test-results"), { recursive: true });
  for (const width of [360, 600, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 1), false, `overflow at ${width}`);
    if ([360, 1440].includes(width)) await page.screenshot({ path: resolve(`test-results/rtk-${width}.png`), fullPage: true });
  }
  await tool.getByRole("button", { name: "清空效果记录", exact: true }).click();
  await tool.getByRole("button", { name: "确认清理", exact: true }).click();
  await tool.getByText(/尚无效果记录/).waitFor();
  await page.reload(); await tool.getByRole("combobox", { name: "过滤等级", exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('#rtk-level')?.textContent?.includes('强力'));
  assert.deepEqual(errors, []);
  console.log("RTK UI passed: install/cancel/reload, tool switching/drafts, levels/conflicts, stats/clear, diagnostic, 4 responsive widths.");
} finally { f.release(); await browser.close(); await app.close(); rmSync(f.root, { recursive: true, force: true }); }
