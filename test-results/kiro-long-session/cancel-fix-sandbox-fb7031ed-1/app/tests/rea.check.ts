import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { chromium } from "playwright";
import { startServer } from "../src/server/index.js";
import { reaConfigPath, reaPackageRoot } from "../src/server/integrations/rea-runtime.js";
import { reaFixture } from "./rea-fixture.js";

const root = mkdtempSync(join(tmpdir(), "axiom-rea-ui-")), fixture = reaFixture();
let release!: () => void;
fixture.hold(new Promise<void>(resolve => { release = resolve; }));
const app = await startServer({ root, port: 0, rea: fixture.dependencies,
  openCli: { execute: async () => { throw Error("OpenCLI excluded from REA test"); }, locateNpm: () => "unused-npm.js" } });
const browser = await chromium.launch({ headless: true, executablePath: process.env.AXIOM_TEST_BROWSER });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: "reduce" });
const errors: string[] = [];
page.on("pageerror", error => errors.push(error.message));
try {
  await page.goto(app.origin + "/tools.html#rea");
  const install = page.getByRole("button", { name: "安装 REA", exact: true });
  await install.waitFor();
  assert.equal(await page.getByRole("button", { name: "安装 Skill", exact: true }).isDisabled(), true);
  assert.equal(await page.getByRole("button", { name: "安装 MCP", exact: true }).isDisabled(), true);
  await page.waitForFunction(() => !(document.querySelector("#rea .btn-primary") as HTMLButtonElement)?.disabled);
  await install.click();
  await page.getByRole("button", { name: "取消操作", exact: true }).waitFor();
  await page.reload();
  await page.getByRole("button", { name: "取消操作", exact: true }).click();
  await page.getByText("操作已取消；当前版本保持不变。", { exact: true }).waitFor();
  assert.equal(fixture.calls.filter(args => args[1] === "install").length, 1);
  release();
  await install.click();
  await page.getByText("REA 与技能已接入；已有会话请重新加载技能与 MCP。", { exact: true }).waitFor();
  assert.equal(JSON.parse(readFileSync(reaConfigPath(root), "utf8")).installation.version, "6.7.0");
  assert.ok(JSON.parse(readFileSync(reaConfigPath(root), "utf8")).installation.runtime);
  assert.match(await page.locator("#rea .tools-facts").innerText(), /组件专用/);
  assert.match(await page.locator("#rea .tools-diagnostic").innerText(), /1 个工具/);
  const enabled = page.locator("#rea input[type=checkbox]");
  await enabled.uncheck();
  await page.getByText("默认设置已保存；已有会话请在技能与 MCP 面板重新加载。", { exact: true }).waitFor();
  assert.equal(JSON.parse(readFileSync(reaConfigPath(root), "utf8")).enabled, false);
  await page.reload();
  await page.waitForFunction(() => !(document.querySelector("#rea input") as HTMLInputElement)?.checked);
  await page.getByRole("button", { name: "检测 REA 连接", exact: true }).click();
  await page.getByText("检查完成。", { exact: true }).waitFor();
  await page.locator("#rea .tools-diagnostic").waitFor();
  const installSkill = page.getByRole("button", { name: "安装 Skill", exact: true });
  const installMcp = page.getByRole("button", { name: "安装 MCP", exact: true });
  await page.getByRole("button", { name: "卸载 Skill", exact: true }).click();
  await page.getByText("Skill 已卸载；已有会话请在技能与 MCP 面板调整选择并重新加载。", { exact: true }).waitFor();
  assert.equal(JSON.parse(readFileSync(reaConfigPath(root), "utf8")).skillInstalled, false);
  assert.equal(await installMcp.isDisabled(), true);
  await page.reload();
  await installSkill.click();
  await page.getByText("Skill 已安装；已有会话请在技能与 MCP 面板调整选择并重新加载。", { exact: true }).waitFor();
  assert.equal(JSON.parse(readFileSync(reaConfigPath(root), "utf8")).skillInstalled, true);
  await page.getByRole("button", { name: "卸载 MCP", exact: true }).click();
  await page.getByText("MCP 已卸载；已有会话请在技能与 MCP 面板调整选择并重新加载。", { exact: true }).waitFor();
  assert.equal(JSON.parse(readFileSync(reaConfigPath(root), "utf8")).mcpInstalled, false);
  assert.equal(await installSkill.isDisabled(), true);
  await page.reload();
  await installMcp.click();
  await page.getByText("MCP 已安装；已有会话请在技能与 MCP 面板调整选择并重新加载。", { exact: true }).waitFor();
  assert.equal(JSON.parse(readFileSync(reaConfigPath(root), "utf8")).mcpInstalled, true);
  const entry = join(reaPackageRoot(root)!, "scripts", "rea.mjs"), entryText = readFileSync(entry, "utf8");
  rmSync(entry);
  await page.locator("#rea").getByRole("button", { name: "检查安装", exact: true }).click();
  const mcpError = page.locator('#rea [aria-labelledby="rea-mcp-heading"] [role=alert]');
  await mcpError.waitFor();
  await page.getByRole("button", { name: "卸载 Skill", exact: true }).click();
  await page.getByText("Skill 已卸载；已有会话请在技能与 MCP 面板调整选择并重新加载。", { exact: true }).waitFor();
  assert.equal(await mcpError.isVisible(), true, "component health errors must remain visible after another successful operation");
  await page.getByRole("button", { name: "卸载 MCP", exact: true }).click();
  await page.getByText("MCP 已卸载；已有会话请在技能与 MCP 面板调整选择并重新加载。", { exact: true }).waitFor();
  await mcpError.waitFor({ state: "detached" });
  writeFileSync(entry, entryText);
  await installSkill.click();
  await page.getByText("Skill 已安装；已有会话请在技能与 MCP 面板调整选择并重新加载。", { exact: true }).waitFor();
  await installMcp.click();
  await page.getByText("MCP 已安装；已有会话请在技能与 MCP 面板调整选择并重新加载。", { exact: true }).waitFor();
  assert.equal(fixture.calls.filter(args => args[1] === "install").length, 2, "component reinstall must reuse the local package");
  fixture.setLatest("6.8.0");
  await page.locator("#rea").getByRole("button", { name: "检查更新", exact: true }).click();
  await page.locator("#rea").getByText("v6.8.0", { exact: true }).waitFor();
  fixture.fail();
  await page.getByRole("button", { name: "更新 REA", exact: true }).click();
  await page.locator("#rea [role=alert]").filter({ hasText: "network failure" }).waitFor();
  await page.reload();
  await page.locator("#rea [role=alert]").filter({ hasText: "network failure" }).waitFor();
  assert.equal(JSON.parse(readFileSync(reaConfigPath(root), "utf8")).installation.version, "6.7.0");
  assert.ok(!(await page.locator("#rea").innerText()).includes("secret-value"));
  const managedConfig = readFileSync(reaConfigPath(root), "utf8"), legacy = JSON.parse(managedConfig);
  delete legacy.installation.runtime;
  writeFileSync(reaConfigPath(root), JSON.stringify(legacy));
  await page.reload();
  await page.locator("#rea .tools-facts").getByText(/旧版共享环境/).waitFor();
  await page.getByText("现有安装保持不变。重新安装或更新后使用与目标 REA 版本兼容的独立 Node/npm；不需要升级后台或系统 Node。", { exact: true }).waitFor();
  writeFileSync(reaConfigPath(root), managedConfig);
  await page.reload();
  await page.locator("#rea .tools-facts").getByText(/组件专用/).waitFor();
  mkdirSync(resolve("test-results"), { recursive: true });
  for (const width of [360, 430, 820, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 1), false, `horizontal overflow at ${width}`);
    if ([360, 1440].includes(width)) await page.screenshot({ path: resolve(`test-results/rea-${width}.png`), fullPage: true });
  }
  assert.deepEqual(errors, []);
  console.log("REA UI passed: independent Skill/MCP install/uninstall and persisted choices, install/cancel/reload, persistent defaults, actual fixture MCP diagnostic, failed update preservation, four responsive widths.");
} finally { release(); await browser.close(); await app.close(); rmSync(root, { recursive: true, force: true }); }
